"""Generate UMAP fuzzy simplicial set fixtures by calling umap-learn.

The points are small integers from a seeded LCG, so every squared distance is
an exact integer below 2**24 and its f32 square root is correctly rounded on
both sides. Only the kNN indices (integers) and umap-learn's output CSR
cross as text.

Run from the repo root:
  uv run --with umap-learn python dev/gen_umap_graph_fixtures.py \
      > crates/bixverse-methods/tests/umap_graph_fixtures/mod.rs
  rustfmt --edition 2024 crates/bixverse-methods/tests/umap_graph_fixtures/mod.rs
"""

import numpy as np
import umap
from umap.umap_ import fuzzy_simplicial_set

N = 150
DIM = 4
COORD_RANGE = 21
N_NEIGHBORS = 11
LCG_SEED = 2024


def lcg(n, seed=LCG_SEED):
    """Numerical Recipes LCG. Mirrored exactly on the Rust side."""
    x = seed
    for _ in range(n):
        x = (1664525 * x + 1013904223) % (2**32)
        yield x


pts = np.array([x % COORD_RANGE for x in lcg(N * DIM)], dtype=np.int64).reshape(N, DIM)
assert len({tuple(p) for p in pts}) == N, "duplicate points, change the seed"

sq = ((pts[:, None, :] - pts[None, :, :]) ** 2).sum(-1)
# ties broken by index so the order is reproducible
order = np.lexsort((np.broadcast_to(np.arange(N), (N, N)), sq), axis=1)
knn_idx = order[:, :N_NEIGHBORS]
assert (knn_idx[:, 0] == np.arange(N)).all()
knn_dist = np.sqrt(np.take_along_axis(sq, knn_idx, 1).astype(np.float32))

out = []


def emit(line=""):
    out.append(line)


def arr(name, ty, vals, fmt):
    emit(f"pub const {name}: [{ty}; {len(vals)}] = [{', '.join(fmt(v) for v in vals)}];")


emit("#![allow(clippy::excessive_precision)]")
emit("//! Generated by dev/gen_umap_graph_fixtures.py. Do not edit.")
emit(f"//! umap-learn {umap.__version__}")
emit()
emit(f"pub const N: usize = {N};")
emit(f"pub const DIM: usize = {DIM};")
emit(f"pub const COORD_RANGE: u32 = {COORD_RANGE};")
emit(f"pub const LCG_SEED: u32 = {LCG_SEED};")
emit(f"pub const K: usize = {N_NEIGHBORS - 1};")
arr("IDX", "u32", knn_idx[:, 1:].ravel().tolist(), str)

for name, lc, mix in [("UNION", 1.0, 1.0), ("MIXED", 1.5, 0.5)]:
    g, _, _ = fuzzy_simplicial_set(
        np.zeros((N, 1)),
        N_NEIGHBORS,
        None,
        "euclidean",
        knn_indices=knn_idx,
        knn_dists=knn_dist,
        local_connectivity=lc,
        set_op_mix_ratio=mix,
    )
    g = g.tocsr()
    g.sort_indices()
    emit(f"pub const {name}_LOCAL_CONNECTIVITY: f32 = {lc};")
    emit(f"pub const {name}_MIX_RATIO: f32 = {mix};")
    arr(f"{name}_INDPTR", "usize", g.indptr.tolist(), str)
    arr(f"{name}_INDICES", "u32", g.indices.tolist(), str)
    arr(f"{name}_DATA", "f32", g.data.astype(np.float32).tolist(), lambda v: f"{v:.9e}")

print("\n".join(out))
