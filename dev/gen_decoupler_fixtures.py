"""Generate decoupler ULM / MLM parity fixtures by calling the reference.

The inputs are rebuilt on the Rust side from the same seeded LCG, with values
formed by exactly-representable f64 arithmetic, so no float data crosses as
text. Only decoupler's outputs are emitted. The method functions are called
directly on dense arrays, which skips decoupler's tmin pruning and empty
feature removal and leaves just the models.

Run from the repo root:
  uv run --python 3.12 --with /Users/gregorlueg/repos/others/decoupler \
      python dev/gen_decoupler_fixtures.py > crates/bixverse-rs/tests/decoupler_fixtures/mod.rs
  rustfmt --edition 2024 crates/bixverse-rs/tests/decoupler_fixtures/mod.rs
"""

from importlib.metadata import version

import numpy as np
from decoupler.mt._mlm import _func_mlm
from decoupler.mt._ulm import _func_ulm

N_FEATURES = 200
N_OBS = 6
LCG_SEED = 4242

# feature indices per set; sets 1 and 2 overlap on purpose
SETS = [
    list(range(0, 15)),
    [3 * i for i in range(20)],
    [3 * i + 30 for i in range(10)] + [100, 101, 102],
    [150 + 2 * i for i in range(12)],
]

out = []


def emit(line=""):
    out.append(line)


def f(x):
    """Full-precision f64 literal."""
    return f"{float(x):.17e}"


def lcg(n, seed=LCG_SEED):
    """Numerical Recipes LCG. Mirrored exactly on the Rust side."""
    x = seed
    for _ in range(n):
        x = (1664525 * x + 1013904223) % (2**32)
        yield x


def data():
    # observation-major, like the Rust side's fill order
    vals = [x / 4294967296.0 * 6.0 - 3.0 for x in lcg(N_OBS * N_FEATURES)]
    return np.array(vals).reshape(N_OBS, N_FEATURES)


def weights():
    # quarters in [-1, 1] without zero: exact in both languages
    raw = iter(lcg(sum(len(s) for s in SETS), seed=LCG_SEED + 1))
    w = []
    for s in SETS:
        ks = [next(raw) % 8 for _ in s]
        w.append([(k - 4) / 4.0 if k < 4 else (k - 3) / 4.0 for k in ks])
    return w


def adj(ws):
    a = np.zeros((N_FEATURES, len(SETS)))
    for j, (s, w) in enumerate(zip(SETS, ws)):
        a[s, j] = w
    return a


def emit_mat(name, m):
    emit(f"pub const {name}: [[f64; {m.shape[1]}]; {m.shape[0]}] = [")
    for row in m:
        emit("    [" + ", ".join(f(x) for x in row) + "],")
    emit("];")


mat = data()
ws = weights()

emit("#![allow(clippy::excessive_precision)]")
emit("//")
emit(f"// Generated by dev/gen_decoupler_fixtures.py against decoupler {version('decoupler')}.")
emit("// Do not edit by hand. Matrices are observations x sets.")
emit()
emit(f"pub const N_FEATURES: usize = {N_FEATURES};")
emit(f"pub const N_OBS: usize = {N_OBS};")
emit(f"pub const LCG_SEED: u64 = {LCG_SEED};")
emit()
for j, s in enumerate(SETS):
    emit(f"pub const SET_{j}: [usize; {len(s)}] = [{', '.join(map(str, s))}];")
emit()

for label, a in [("BIN", adj([[1.0] * len(s) for s in SETS])), ("W", adj(ws))]:
    for method, func in [("ULM", _func_ulm), ("MLM", _func_mlm)]:
        t, pv = func(mat, a, tval=True)
        coef, _ = func(mat, a, tval=False)
        emit_mat(f"{method}_{label}_T", t)
        emit_mat(f"{method}_{label}_COEF", coef)
        emit_mat(f"{method}_{label}_P", pv)
        emit()

print("\n".join(out))
