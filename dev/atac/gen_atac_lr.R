# Parity fixture for crates/bixverse-sc/src/sc_analysis/dge_lr.rs: Seurat's
# logistic regression test (`LRDETest`, what `FindMarkers(test.use = "LR")`
# runs) with the library size as the latent variable, as the Signac vignettes
# use it for differential accessibility.
#
# Regenerates crates/bixverse-sc/tests/dge_lr_fixtures/mod.rs. Run from the
# repository root with
#   Rscript dev/atac/gen_atac_lr.R > crates/bixverse-sc/tests/dge_lr_fixtures/mod.rs
#
# The counts come from a Numerical Recipes LCG and a modulo, so both languages
# build the identical integer matrix without any data crossing as text. The
# normalised layer is the store's, `log1p(count / lib * 1e4)`, computed on each
# side in double precision.
#
# Seurat 6.0.0, lmtest 0.9.40.

suppressPackageStartupMessages(library(Seurat))

N_FEAT <- 40L
N_CELLS <- 240L
N_GRP_1 <- 100L
LCG_SEED <- 20261119

lcg_state <- LCG_SEED
lcg_next <- function() {
  lcg_state <<- (1664525 * lcg_state + 1013904223) %% 4294967296
  lcg_state
}

# Group 1 cells sit one depth step higher, so depth confounds the groups and
# the latent variable has something to absorb. Every third feature is also
# genuinely up in group 1. The last feature is detected in group 1 only, i.e.
# perfectly separated.
group_1 <- seq_len(N_CELLS) <= N_GRP_1
depth <- vapply(seq_len(N_CELLS), function(c) {
  1 + lcg_next() %% 4 + as.numeric(group_1[c])
}, numeric(1))

counts <- matrix(0, nrow = N_FEAT, ncol = N_CELLS)
for (f in seq_len(N_FEAT)) {
  for (c in seq_len(N_CELLS)) {
    r <- lcg_next()
    if (f == N_FEAT) {
      counts[f, c] <- if (group_1[c]) 1 + r %% 3 else 0
    } else {
      up <- if (group_1[c] && (f - 1L) %% 3 == 0) 8 else 0
      modulus <- 5 + (f - 1L) %% 4 + 2 * depth[c] + up
      counts[f, c] <- max(0, r %% modulus - 4)
    }
  }
}

lib <- colSums(counts)
data_norm <- log1p(sweep(counts, 2, lib, "/") * 1e4)

cells <- paste0("c", seq_len(N_CELLS))
features <- paste0("f", seq_len(N_FEAT))
dimnames(data_norm) <- list(features, cells)
latent <- data.frame(nCount_peaks = lib, row.names = cells)

res <- Seurat:::LRDETest(
  data.use = data_norm,
  cells.1 = cells[group_1],
  cells.2 = cells[!group_1],
  latent.vars = latent,
  verbose = FALSE
)

fmt <- function(x) paste(sprintf("%.17e", x), collapse = ",\n    ")

cat("// R emits seventeen significant digits; trimming them would mean editing\n")
cat("// generated values.\n")
cat("#![allow(clippy::excessive_precision)]\n\n")
cat("//! Generated by dev/atac/gen_atac_lr.R (Seurat 6.0.0, lmtest 0.9.40). Do not\n")
cat("//! edit by hand.\n\n")
cat(sprintf("pub const N_FEAT: usize = %d;\n", N_FEAT))
cat(sprintf("pub const N_CELLS: usize = %d;\n", N_CELLS))
cat(sprintf("pub const N_GRP_1: usize = %d;\n", N_GRP_1))
cat(sprintf("pub const LCG_SEED: u64 = %d;\n\n", LCG_SEED))
cat("/// Seurat's `LRDETest` p-value per feature, `group ~ GENE + nCount_peaks`\n")
cat("/// against `group ~ nCount_peaks`.\n")
cat("pub const P_VALUE: &[f64] = &[\n    ")
cat(fmt(res$p_val))
cat(",\n];\n")
