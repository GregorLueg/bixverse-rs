# The predictors come from a Numerical Recipes LCG, so both languages build the
# identical matrix without any data crossing as text. Three cases cover the
# three weight branches of the kernel algorithm: one response, q < p and q >= p.

N_OBS <- 40L
N_PRED <- 15L
LCG_SEED <- 20261124

lcg_state <- LCG_SEED
lcg_next <- function() {
  lcg_state <<- (1664525 * lcg_state + 1013904223) %% 4294967296
  lcg_state
}

# two in five entries are zero, the rest k / 3 for k in 0..12
x <- matrix(0, nrow = N_OBS, ncol = N_PRED)
for (i in seq_len(N_OBS)) {
  for (j in seq_len(N_PRED)) {
    s <- lcg_next()
    x[i, j] <- if (s %% 5 < 2) 0 else (s %% 13) / 3
  }
}

obs <- 0:(N_OBS - 1L)
one_hot <- function(cls, k) outer(cls, 0:(k - 1L), "==") * 1

cases <- list(
  single = list(x = x, y = matrix(x[, 1] + x[, 2] - x[, 3] + obs %% 4, ncol = 1), ncomp = 4L),
  multi = list(x = x, y = one_hot(obs %% 3, 3L), ncomp = 5L),
  wide = list(x = x[, 1:3], y = one_hot(obs %% 4, 4L), ncomp = 2L)
)

# Rust wants a decimal point on every f64 literal
fmt <- function(v) {
  s <- sprintf("%.17g", v)
  paste(ifelse(grepl("[.e]", s), s, paste0(s, ".0")), collapse = ", ")
}
emit <- function(name, m) {
  # row-major
  cat(sprintf("pub const %s: &[f64] = &[%s];\n", name, fmt(as.vector(t(as.matrix(m))))))
}

cat("//! Generated by dev/gen_pls_fixtures.R against pls", as.character(packageVersion("pls")), "\n")
cat("//! Do not edit by hand. Matrices are row-major.\n\n")
cat("#![allow(dead_code, clippy::excessive_precision)]\n\n")
cat(sprintf("pub const N_OBS: usize = %d;\npub const N_PRED: usize = %d;\npub const LCG_SEED: u64 = %d;\n\n", N_OBS, N_PRED, LCG_SEED))

for (nm in names(cases)) {
  cs <- cases[[nm]]
  fit <- pls::kernelpls.fit(cs$x, cs$y, ncomp = cs$ncomp)
  up <- toupper(nm)
  cat(sprintf("pub const %s_NCOMP: usize = %d;\n", up, cs$ncomp))
  cat(sprintf("pub const %s_NPRED: usize = %d;\n", up, ncol(cs$x)))
  cat(sprintf("pub const %s_NRESP: usize = %d;\n", up, ncol(cs$y)))
  emit(paste0(up, "_Y"), cs$y)
  emit(paste0(up, "_PROJECTION"), unclass(fit$projection))
  emit(paste0(up, "_WEIGHTS"), unclass(fit$loading.weights))
  emit(paste0(up, "_X_LOADINGS"), unclass(fit$loadings))
  emit(paste0(up, "_Y_LOADINGS"), unclass(fit$Yloadings))
  emit(paste0(up, "_SCORES"), unclass(fit$scores))
  emit(paste0(up, "_X_MEANS"), fit$Xmeans)
  cat("\n")
}
