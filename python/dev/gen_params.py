@beartype
def class_name(spec: str) -> str:
    """The Python class for a spec: `sc_` dropped, `Params` unless a block."""
    stem = spec.removeprefix("sc_")
    pascal = "".join(part.capitalize() for part in stem.split("_"))
    if spec.endswith(("_defaults", "_default")):
        return pascal
    return f"{pascal}Params"


@beartype
def attr_name(name: str) -> str:
    """A field name that is legal in Python (`lambda` becomes `lambda_`)."""
    return f"{name}_" if keyword.iskeyword(name) else name


#: Spec prose that names the R package, as Python readers should see it.
SPEC_PROSE: tuple[tuple[str, str], ...] = (
    ("Defaults are the R package's own.", "Defaults follow the `nebula` package."),
    (
        " below 30 cells per subject, as the R package does.",
        " below 30 cells per subject.",
    ),
    (
        "The R package only honours this for `NBLMM`, which the Rust port does not "
        "implement, so this arm has not been validated against an R reference.",
        "This arm has not been validated against a reference.",
    ),
    ("as in R harmony v2,", "as in Harmony v2,"),
    ("to get a call instead of `NA`.", "to get a call instead of null."),
    ("Symphony R default is 0.1.", "The Symphony default is 0.1."),
    ("Symphony R hardcodes 1.0.", "Symphony fixes it at 1.0."),
)


@beartype
def clean_doc(doc: str, names: dict[str, str]) -> str:
    """R idioms in the spec prose, rewritten for Python readers."""
    doc = re.sub(
        r"\[(?:bixverse::)?params_(\w+)\(\)\]",
        lambda m: f"`{names.get(m.group(1), m.group(1))}`",
        doc,
    )
    doc = re.sub(r"\[(?:bixverse::)?(\w+)\(\)\]", r"`\1()`", doc)
    doc = re.sub(r"\b(\d+)L\b", r"\1", doc)
    for r_word, py_word in (("NULL", "None"), ("TRUE", "True"), ("FALSE", "False")):
        doc = re.sub(rf"\b{r_word}\b", py_word, doc)
    doc = re.sub(r"`(\w+)_sc\(\)`", r"`\1()`", doc)
    doc = " ".join(doc.split())
    for old, new in SPEC_PROSE:
        doc = doc.replace(old, new)
    return doc


@beartype
def parse_range(rng: str | None) -> tuple[str, str, bool, bool] | None:
    """Split a checkmate range such as `(0, 1]` into bounds and openness."""
    if not rng:
        return None
    m = re.fullmatch(r"([\[(])\s*([^,]*)\s*,\s*([^\])]*)\s*([\])])", rng.strip())
    if m is None:
        raise ValueError(f"unparsed range {rng!r}")
    lo = m.group(2).strip() or "None"
    hi = m.group(3).strip() or "None"
    return lo, hi, m.group(1) == "(", m.group(4) == ")"


@beartype
def py_literal(value: object, kind: str) -> str:
    """Source for a default value of the given field kind."""
    if value is None:
        return "None"
    if isinstance(value, list):
        return "(" + "".join(f"{py_literal(v, kind)}, " for v in value) + ")"
    if kind == "dbl" and isinstance(value, int | float):
        return repr(float(value))
    return repr(value)


@beartype
def py_type(spec: str, f: dict) -> str:
    """The annotation for one field."""
    kind = f["type"]
    if kind == "free":
        if (spec, f["name"]) in FREE_TYPES:
            return FREE_TYPES[(spec, f["name"])]
        default = f["default"]
        kind = {bool: "lgl", int: "int", float: "dbl", str: "chr"}[type(default)]
    if kind == "choice":
        base = "Literal[" + ", ".join(repr(c) for c in f["choices"]) + "]"
    else:
        base = SCALAR_TYPES[kind]
    if f["len"] != "1":
        base = f"tuple[{base}, ...]"
    if (
        f["null_ok"]
        or f["derived"] is not None
        or (f["default"] is None and not f["required"])
    ):
        base = f"{base} | None"
    return base


@beartype
def r_expr_to_py(expr: str, fields: set[str]) -> str:
    """A derived override (`neighbours_within_batch * 2L`) as Python on `self`."""
    expr = re.sub(r"\b(\d+)L\b", r"\1", expr)
    return re.sub(
        r"\b([A-Za-z_]\w*)\b",
        lambda m: (
            f"self.{attr_name(m.group(1))}" if m.group(1) in fields else m.group(1)
        ),
        expr,
    )


@beartype
def emit_field(spec: str, f: dict) -> str:
    """One dataclass field line."""
    name = attr_name(f["name"])
    ann = py_type(spec, f)
    if f["required"]:
        return f"    {name}: {ann}"
    if f["derived"] is not None:
        return f"    {name}: {ann} = None"
    if isinstance(f["default"], dict):
        return f"    {name}: {ann} = field(default_factory=lambda: {f['default']!r})"
    kind = f["type"] if f["type"] != "free" else ""
    return f"    {name}: {ann} = {py_literal(f['default'], kind)}"


@beartype
def emit_checks(f: dict, fields: set[str]) -> list[str]:
    """`__post_init__` lines for one field: derived default, length, range."""
    name = attr_name(f["name"])
    out = []
    if f["derived"] is not None:
        expr = r_expr_to_py(f["derived"], fields)
        out.append(f"        if self.{name} is None:")
        out.append(f'            object.__setattr__(self, "{name}", {expr})')
    if f["len"] == "+":
        out.append(f'        check_len("{name}", self.{name})')
    rng = f["range"]
    if rng is None and f["check_as"]:
        m = re.search(r"([\[(].*[\])])", f["check_as"])
        rng = m.group(1) if m else None
    bounds = parse_range(rng)
    if bounds is not None:
        lo, hi, lo_open, hi_open = bounds
        args = f'"{name}", self.{name}, {lo}, {hi}, {lo_open}, {hi_open}'
        out.append(f"        check_range({args})")
    return out


@beartype
def emit_class(spec: dict, names: dict[str, str]) -> str:
    """One dataclass for one flattened spec."""
    cname = names[spec["name"]]
    fields = spec["fields"]
    field_set = {f["name"] for f in fields}
    summary = clean_doc(spec["title"], names) or f"Parameters for `{spec['name']}`."
    doc = [f'    """{summary}', ""]
    if spec["description"]:
        doc += textwrap.wrap(
            clean_doc(spec["description"], names),
            84,
            initial_indent="    ",
            subsequent_indent="    ",
        )
        doc.append("")
    doc.append("    Attributes:")
    for f in fields:
        text = clean_doc(f["doc"], names) or "Undocumented."
        doc += textwrap.wrap(
            f"{attr_name(f['name'])}: {text}",
            84,
            initial_indent="        ",
            subsequent_indent="            ",
        )
    doc.append('    """')
    body = [emit_field(spec["name"], f) for f in fields]
    checks = [line for f in fields for line in emit_checks(f, field_set)]
    checks.append("        _extras.run(self)")
    return "\n".join(
        [
            "@beartype(conf=_CONF)",
            "@dataclass(frozen=True, kw_only=True, slots=True)",
            f"class {cname}:",
            *doc,
            "",
            *body,
            "",
            "    def __post_init__(self) -> None:",
            *checks,
            "",
            "",
        ]
    )


@beartype
def main(
    checkout: Path,
    wanted: tuple[str, ...],
    out: Path,
    header: str,
    base_dir: Path | None = None,
) -> None:
    """Dump the specs through R, then write the generated module.

    Args:
        checkout: The R package whose specs to dump.
        wanted: The spec names.
        out: The module to write.
        header: The module header, imports included.
        base_dir: A bixverse checkout whose specs `checkout` merges from.
    """
    env = dict(os.environ)
    if base_dir is not None:
        env["BIXVERSE_BASE_DIR"] = str(base_dir)
    with tempfile.TemporaryDirectory() as tmp:
        dump = Path(tmp) / "specs.json"
        subprocess.run(
            [
                "Rscript",
                str(HERE / "dump_param_specs.R"),
                str(checkout),
                str(dump),
                *wanted,
            ],
            check=True,
            env=env,
        )
        specs = json.loads(dump.read_text())
    # R drops list elements assigned NULL, so absent keys mean null.
    keys = ("default", "range", "choices", "letter", "check_as", "origin", "derived")
    for s in specs.values():
        for f in s.get("fields", []):
            for k in keys:
                f.setdefault(k, None)
    names = {s: class_name(s) for s in wanted}
    if len(set(names.values())) != len(names):
        raise SystemExit("class name collision")
    # doc links may point at the CPU bundles
    doc_names = {**{s: class_name(s) for s in SPECS}, **names}
    generated = [s for s in specs.values() if not s["handwritten"]]
    for s in generated:
        s["fields"] = [f for f in s["fields"] if (s["name"], f["name"]) not in EXCLUDE]
    renamed = {
        names[s["name"]]: {
            attr_name(f["name"]): f["name"]
            for f in s["fields"]
            if attr_name(f["name"]) != f["name"]
        }
        for s in generated
    }
    renamed = {k: v for k, v in renamed.items() if v}
    parts = [header]
    parts += [emit_class(s, doc_names) for s in generated]
    parts.append(
        "#: Python attribute to Rust key, where the key is a Python keyword.\n"
        f"RUST_NAMES: dict[str, dict[str, str]] = {renamed!r}\n\n"
        f"__all__ = {sorted(names[s['name']] for s in generated)!r}\n"
    )
    out.write_text("".join(parts))
    subprocess.run(["ruff", "check", "--select", "F401", "--fix", "-q", str(out)])
    subprocess.run(["ruff", "format", str(out)], check=True)
    skipped = sorted(s["name"] for s in specs.values() if s["handwritten"])
    print(f"wrote {len(generated)} classes to {out}; hand-written: {skipped}")


if __name__ == "__main__":
    match sys.argv[1:]:
        case ["--gpu", gpu_dir, bixverse_dir]:
            main(
                Path(gpu_dir).expanduser(),
                GPU_SPECS,
                GPU_OUT,
                GPU_HEADER,
                Path(bixverse_dir).expanduser(),
            )
        case [bixverse_dir]:
            main(Path(bixverse_dir).expanduser(), SPECS, OUT, HEADER)
        case _:
            raise SystemExit(__doc__)
