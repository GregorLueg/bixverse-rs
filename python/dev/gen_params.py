"""Generate `bixverse/params/_generated.py` from the bixverse R param specs.

Run from `python/`:

    uv run python dev/gen_params.py ~/repos/shared/bixverse

and for the GPU wheel, from the bixverse.gpu specs (bixverse supplies the
blocks they merge):

    uv run python dev/gen_params.py --gpu ~/repos/shared/bixverse.gpu \
        ~/repos/shared/bixverse

`dev/dump_param_specs.R` flattens the devforge specs to JSON (and checks every
default against the R package's generated constructors); this script turns the
JSON into one frozen dataclass per spec. The output is committed and never
edited by hand. Cross-field rules that devforge carries as R code
(`extra_ctor`) live in `bixverse/params/_extras.py` instead.
"""

