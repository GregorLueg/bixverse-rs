class CistargetParams:
    """Wrapper function to CisTarget parameters

    `auc_threshold` and `max_rank` are two different cutoffs and are easy to
    confuse. The first truncates the recovery curve used to score motif enrichment,
    the second sets how deep into the ranking the background curve (mean + 2 SD
    across all motifs) is built, and therefore where the leading edge cuts.
    RcisTarget uses `maxRank = 5000` and `nMean = 100`; the defaults here follow it.
    `auc_threshold` follows pySCENIC at 5%, RcisTarget itself uses 3%.

    Attributes:
        auc_threshold: Numeric between 0 and 1. Proportion of genes to use for AUC
            threshold calculation. Default is 0.05 (5% of genes).
        nes_threshold: Normalised Enrichment Score threshold for significant motifs.
            Default is 3.0.
        max_rank: Depth of the recovery curves used to derive the background and the
            leading edge. Clamped to the number of genes in the ranking database.
            Default is 5000, the RcisTarget value.
        n_mean: Window for the rolling mean smoothing the background recovery curve.
            Only read when `rcc_method = "approx"`. Default is 100, the RcisTarget
            value.
        rcc_method: Method for recovery curve calculation. Either "approx"
            (approximate, faster) or "icistarget" (exact, slower).
        high_conf_cats: Annotation categories considered high confidence. Default
            includes direct annotations and orthology-based inferences.
        low_conf_cats: Annotation categories considered lower confidence. Default
            includes motif similarity-based inferences.
    """

    auc_threshold: float = 0.05
    nes_threshold: float = 3.0
    max_rank: int = 5000
    n_mean: int = 100
    rcc_method: Literal["approx", "icistarget"] = "approx"
    high_conf_cats: tuple[str, ...] = (
        "directAnnotation",
        "inferredBy_Orthology",
    )
    low_conf_cats: tuple[str, ...] = (
        "inferredBy_MotifSimilarity",
        "inferredBy_MotifSimilarity_n_Orthology",
    )

    def __post_init__(self) -> None:
        check_range("auc_threshold", self.auc_threshold, 0, 1, False, False)
        check_range("max_rank", self.max_rank, 1, None, False, True)
        check_range("n_mean", self.n_mean, 1, None, False, True)
        check_len("high_conf_cats", self.high_conf_cats)
        check_len("low_conf_cats", self.low_conf_cats)
