class HarmonyV2GpuParams:
    """Default parameters for Harmony v2 GPU batch correction

    Attributes:
        k: Number of clusters for k-means clustering. If not provided, it will be
            automatically determined as `min(round(N / 30), 100)`.
        sigma: Per-cluster diversity weights. Either a single value (broadcast to
            all clusters) or a vector of length k.
        theta: Per-variable diversity penalty. Must be a single value; only one
            batch covariate is supported on the GPU path.
        lambda_: Ridge regression penalty for the linear model. Typically a single
            value. Ignored when `use_dynamic_lambda = True`.
        max_iter_kmeans: Maximum number of k-means Jacobi sweeps per Harmony round.
        max_iter_harmony: Maximum number of Harmony outer iterations.
        epsilon_kmeans: Convergence threshold for k-means clustering.
        epsilon_harmony: Convergence threshold for Harmony.
        window_size: Number of previous iterations to consider when checking
            convergence.
        alpha: Scaling factor for dynamic lambda estimation. Must be in (0, 1). Only
            relevant when `use_dynamic_lambda = True`.
        tau: Scaling factor for theta based on batch size. A value of 0 disables
            batch-size scaling of theta.
        batch_proportion_cutoff: Cutoff for pruning batches with small proportions
            during ridge regression.
        use_dynamic_lambda: If `True`, lambda is estimated dynamically per cluster
            instead of using the fixed `lambda` value.
        k_means_iter: Maximum number of k-means iterations for the initial centroid
            computation.
        k_means_init: Initialisation strategy for k-means.
        fixed: If `True`, centroids are fixed after initialisation.
        quantise: If `True`, quantises intermediate values to f16 during k-means.
    """

