class FastClusterGpuParams:
    """Default parameters for GPU fast clustering

    GPU counterpart to `FastClusterParams`. Fast clustering coarsens the cells with
    k-means, builds a graph over the centroids and runs Louvain or Leiden on it. The
    community of each centroid is handed back to its cells. Only the k-means (and
    the cell-mediated top-m search) run on the GPU. The mini-batch k-means knobs are
    gone: the GPU k-means is full-batch Lloyd's.

    Attributes:
        n_centroids: Number of k-means centroids. If `None`, defaults to `floor(4 *
            sqrt(n_cells))`.
        k_means_iter: Maximum number of k-means iterations.
        k_means_init: Initialisation method. One of `"random"`, `"parallel"` or
            `"plusplus"`. If `None`, picked on the Rust side based on the number of
            centroids.
        fixed: Shall k-means run for a fixed number of iterations, without checking
            for convergence. wgpu only; MLX always runs every iteration.
        quantise: Shall the data buffer be held at fp16 on the GPU. Halves the
            buffer and helps when the assignment kernels are memory bound. wgpu
            only.
        dist: Distance for the k-means and the centroid graph.
        cell_mediated: Shall the cell-mediated centroid graph from Secuer be built
            instead of the kNN graph on the centroids. Centroids are then linked by
            the cells that sit near both, so two centroids that are close in space
            but have no cells between them stay apart. If `True`, `centroid_k` and
            `centroid_graph` are ignored.
        n_anchors: Number of nearest centroids each cell links to in the cell-
            mediated graph. Only used if `cell_mediated = True`.
        centroid_k: Neighbours per centroid in the exact centroid kNN. Only used if
            `cell_mediated = False`.
        knn_sym: How to symmetrise the kNN into a graph. Clustering resolutions do
            not carry over between the methods: the `"umap"` and `"knn"` graphs only
            hold kNN pairs, the sNN graph also links cells that share neighbours and
            prunes weak edges. The same resolution can give more or fewer
            communities depending on the data, so retune it when switching.
        snn_similarity: `"snn"` only. `"jaccard"` weighs an edge by the Jaccard
            index of the two (self-inclusive) neighbour sets. `"rank"` takes the
            shared neighbour with the lowest combined rank, so closer shared
            neighbours give heavier edges. Both are scaled to `[0, 1]`.
        pruning: `"snn"` only. Edges below this weight are dropped. For the Jaccard
            weight a threshold `p` keeps pairs that share at least a fraction `2p /
            (1 + p)` of their (self-inclusive) neighbourhoods, rounded up to whole
            cells, so the same value means the same thing at any `k`. The default
            asks for about 12%, i.e. 2 of 16 shared cells at `k = 15`, in line with
            Seurat's `1/15`. Avoid a threshold that equals one of the discrete
            weights exactly, or float rounding decides whether the edge survives.
        rescue: `"snn"` only. Reconnect the small components that pruning cuts off
            via their strongest sNN edge, so they do not turn up as tiny clusters.
        local_connectivity: `"umap"` only. Number of nearest neighbours assumed to
            be fully connected, as in umap-learn.
        mix_ratio: `"umap"` only. `1` is the fuzzy union of the directed kNN
            memberships, `0` the fuzzy intersection (umap-learn's
            `set_op_mix_ratio`).
        binary: `"knn"` only. If `True`, every edge weighs 1. Otherwise mutual
            neighbours weigh 2 and one-sided ones 1.
        algorithm: Community detection on the centroid graph.
        n_iterations: Number of iterations of the community detection. A negative
            value iterates until stable. If `None`, the bixverse default for the
            chosen `algorithm`.
        beta: Leiden only. Randomness of the refinement step.
        min_gain: With a negative `n_iterations`, also stop once an iteration gains
            no more than this in modularity.
        local_moving: `"queue"` is Traag's sequential queue. `"coloured"` moves the
            nodes of one colour class in parallel, which only kicks in on larger
            levels of the graph.
        multi_level: Shall the communities be aggregated and refined in levels.
        max_evals: Cap on the node evaluations per local moving phase, in units of
            the number of nodes.
    """

    n_centroids: int | None = None
    k_means_iter: int = 50
    k_means_init: str | None = None
    fixed: bool = True
    quantise: bool = False
    dist: Literal["euclidean", "cosine"] = "euclidean"
    cell_mediated: bool = False
    n_anchors: int = 5
    centroid_k: int = 15
    knn_sym: Literal["snn", "umap", "knn"] = "snn"
    snn_similarity: Literal["jaccard", "rank"] = "jaccard"
    pruning: float = 0.0625
    rescue: bool = True
    local_connectivity: float = 1.0
    mix_ratio: float = 1.0
    binary: bool = False
    algorithm: Literal["louvain", "leiden"] = "louvain"
    n_iterations: int | None = None
    beta: float = 0.01
    min_gain: float = 0.0
    local_moving: Literal["queue", "coloured"] = "queue"
    multi_level: bool = True
    max_evals: int = 10

    def __post_init__(self) -> None:
        check_range("n_centroids", self.n_centroids, 2, None, False, True)
        check_range("k_means_iter", self.k_means_iter, 1, None, False, True)
        check_range("n_anchors", self.n_anchors, 1, None, False, True)
        check_range("centroid_k", self.centroid_k, 1, None, False, True)
        check_range("pruning", self.pruning, 0, 1, False, False)
        check_range("local_connectivity", self.local_connectivity, 0, None, False, True)
        check_range("mix_ratio", self.mix_ratio, 0, 1, False, False)
        check_range("beta", self.beta, 0, None, True, True)
        check_range("min_gain", self.min_gain, 0, None, False, True)
        check_range("max_evals", self.max_evals, 1, None, False, True)
        _extras.run(self)


