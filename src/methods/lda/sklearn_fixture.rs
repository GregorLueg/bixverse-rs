//! Reference values generated from scikit-learn's `LatentDirichletAllocation`,
//! used to check this crate's variational bound against an independent
//! implementation of the same algorithm.
//!
//! Regenerate with `uv run --with numpy --with scipy --with scikit-learn`,
//! fitting `LatentDirichletAllocation(learning_method="batch", max_iter=200,
//! doc_topic_prior=0.1, topic_word_prior=0.1, mean_change_tol=1e-5,
//! max_doc_update_iter=200, random_state=0)` on [sklearn_corpus], then dumping
//! `components_`, `_unnormalized_transform(X)` and `score(X)`.

use crate::prelude::*;

/// Documents in the reference corpus.
pub(crate) const SKLEARN_N_DOCS: usize = 60;

/// Vocabulary size of the reference corpus.
pub(crate) const SKLEARN_N_TERMS: usize = 40;

/// Topics the reference model was fitted with.
pub(crate) const SKLEARN_K: usize = 4;

/// Both Dirichlet priors of the reference fit.
pub(crate) const SKLEARN_PRIOR: f64 = 0.1;

/// The bound scikit-learn reports for the parameters below.
pub(crate) const SKLEARN_BOUND: f64 = -1899.5186748694439;

/// Reference corpus: four term blocks, each document drawn from one block with
/// a few terms bleeding in from the next so the topics are not trivially
/// separable.
///
/// ### Returns
///
/// A binary documents x terms CSR matrix.
pub(crate) fn sklearn_corpus() -> CompressedSparseData2<f64> {
    let block = SKLEARN_N_TERMS / SKLEARN_K;
    let mut data = Vec::new();
    let mut indices = Vec::new();
    let mut indptr = vec![0u32];
    for d in 0..SKLEARN_N_DOCS {
        let mut row = vec![0.0f64; SKLEARN_N_TERMS];
        let primary = d % SKLEARN_K;
        for t in 0..block {
            if (t + d) % block != 0 {
                row[primary * block + t] = 1.0;
            }
        }
        let next = (primary + 1) % SKLEARN_K;
        for t in 0..block {
            if (t + d * 3) % block == 0 {
                row[next * block + t] = 1.0;
            }
        }
        for (w, &v) in row.iter().enumerate() {
            if v != 0.0 {
                data.push(v);
                indices.push(w as u32);
            }
        }
        indptr.push(data.len() as u32);
    }
    CompressedSparseData2::from_parts(
        data,
        indices,
        indptr,
        None,
        CompressedSparseFormat::Csr,
        (SKLEARN_N_DOCS, SKLEARN_N_TERMS),
    )
}

